"""Port selected source components and extract their original compiled utility rules.
No npm/runtime dependency; generated files must not be edited by hand.
"""
from pathlib import Path
import hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'src/cali'
manifest=json.loads((SRC/'sources.json').read_text())
css=(SRC/'upstream-utilities.css').read_text()
assert hashlib.sha256((SRC/'upstream-utilities.css').read_bytes()).hexdigest()==manifest['compiled_css_sha256']
texts='\n'.join(p.read_text() for p in SRC.iterdir() if p.suffix in {'.html','.js'})
used=set()
for value in re.findall(r'"([^"\n]*)"|\'([^\'\n]*)\'',texts):
    used.update((''.join(value)).split())
used.update({'dark','not-prose','group','prose','dark:prose-invert','ml-1','ml-2'})
identifier=re.compile(r'\.((?:\\[^\r\n]|[-_a-zA-Z0-9\u0080-\uffff])+)')
def classes(selector):
    return {re.sub(r'\\(.)',r'\1',m) for m in identifier.findall(selector)}
def blocks(text):
    i=0;start=0;n=len(text)
    while i<n:
        if text[i].isspace():i+=1;continue
        if text.startswith('/*',i):i=text.index('*/',i+2)+2;continue
        start=i;quote=None
        while i<n:
            c=text[i]
            if c=='\\':i+=2;continue
            if quote:
                if c==quote:quote=None
            elif c in "\"'":quote=c
            elif c in '{;':break
            i+=1
        if i>=n:return
        if text[i]==';':i+=1;continue
        prelude=text[start:i].strip();i+=1;body_start=i;depth=1;quote=None
        while i<n and depth:
            c=text[i]
            if c=='\\':i+=2;continue
            if quote:
                if c==quote:quote=None
            elif c in "\"'":quote=c
            elif text.startswith('/*',i):i=text.index('*/',i+2)+2;continue
            elif c=='{':depth+=1
            elif c=='}':depth-=1
            i+=1
        if depth:raise ValueError('Unbalanced upstream CSS')
        yield prelude,text[body_start:i-1]
matched=set()
def extract(text):
    out=[]
    for selector,body in blocks(text):
        if selector.startswith(('@media','@supports')):
            inner=extract(body)
            if inner:out.append(selector+'{'+inner+'}')
        elif selector.startswith('@keyframes'):
            if selector.split()[-1]=='pulse':out.append(selector+'{'+body+'}')
        elif selector.startswith('@'):continue
        else:
            names=classes(selector)
            # The original ::before/::after content initializer is required by
            # all content:var(--tw-content) utility rules, including card blur.
            initialization=not names and ('--tw-ring-offset-width' in body or (selector in {':after,:before',':before,:after'} and '--tw-content:' in body))
            if not initialization and (not names or not names.issubset(used)):continue
            matched.update(names)
            selector=re.sub(r'(?<![\\\w-])\.dark(?![\\\w-])',':where([data-theme="dark"])',selector)
            # Commas inside :is/:where/attributes stay inside their selector.
            pieces=[];start=0;level=0;quote=None;escaped=False
            for i,c in enumerate(selector):
                if escaped:escaped=False;continue
                if c=='\\':escaped=True;continue
                if quote:
                    if c==quote:quote=None
                elif c in "\"'":quote=c
                elif c in '([':level+=1
                elif c in ')]':level-=1
                elif c==',' and level==0:pieces.append(selector[start:i]);start=i+1
            pieces.append(selector[start:])
            scoped=','.join(':where(.cali-source) '+p.strip() for p in pieces)
            out.append(scoped+'{'+body+'}')
    return ''.join(out)
result=extract(css)
assert ':after,:where(.cali-source) :before{--tw-content:""}' in result, 'Missing upstream pseudo-element initializer'
for critical in ['text-base','md:text-xl','text-4xl','sm:text-5xl','prose','dark:prose-invert','aspect-[240/135]','before:opacity-70','after:backdrop-blur','animate-pulse','md:w-[120%]']:
    if critical not in matched:raise ValueError('Missing upstream utility '+critical)
assets=ROOT/'templates/assets';assets.mkdir(exist_ok=True,parents=True)
(assets/'cali-source.css').write_text('/*! Extracted Tailwind CSS v3.4.1 | MIT | source hash '+manifest['compiled_css_sha256']+' */\n'+(SRC/'preflight.css').read_text()+result+'\n'+(SRC/'bridge.css').read_text())
for original,target in [('card.html','modules/source-card.html'),('post.html','post.html'),('loading.html','modules/source-loading.html'),('icons.html','modules/source-icons.html'),('projects.html','modules/source-projects.html'),('resume.html','modules/source-resume.html'),('projects-page.html','page_projects.html'),('newsletter.html','modules/source-newsletter.html')]:
    path=ROOT/'templates'/target;path.parent.mkdir(exist_ok=True,parents=True)
    path.write_text('<!-- Generated by scripts/build-source.py; edit src/cali/'+original+' -->\n'+(SRC/original).read_text())
for name in ['post.js','navigation.js','projects.js']:
    (assets/('source-'+name)).write_text('/* Generated from src/cali/'+name+'; edit source and rebuild. */\n'+(SRC/name).read_text())
report={'upstream_css_sha256':manifest['compiled_css_sha256'],'used_utilities':sorted(matched),'css_bytes':len(result.encode()),'components':manifest['files']}
(SRC/'build-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(f'Ported source components; extracted {len(matched)} original utility classes ({len(result):,} CSS characters).')
